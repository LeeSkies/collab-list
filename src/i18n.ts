const supportedLanguages = ['ar', 'en', 'fr', 'he'] as const
type SupportedLanguage = (typeof supportedLanguages)[number]
const isSupportedLanguage = (language: string | null): language is SupportedLanguage =>
  language !== null && supportedLanguages.includes(language as SupportedLanguage)
const stored = localStorage.getItem('grocery-language')
const detected =
  (navigator.languages
    .find((language) =>
      supportedLanguages.some((supported) => language.toLowerCase().startsWith(supported))
    )
    ?.split('-')[0] as SupportedLanguage | undefined) ?? 'en'
const initialLanguage = isSupportedLanguage(stored) ? stored : detected

void i18n.use(initReactI18next).init({
  resources,
  lng: initialLanguage,
  fallbackLng: 'en',
  interpolation: { escapeValue: false }
})

export function applyDocumentLanguage(language: string) {
  const locale = isSupportedLanguage(language) ? language : 'en'
  document.documentElement.lang = locale
  document.documentElement.dir = locale === 'ar' || locale === 'he' ? 'rtl' : 'ltr'
  dayjs.locale(locale)
}

applyDocumentLanguage(i18n.language)
i18n.on('languageChanged', (language) => {
  const locale = isSupportedLanguage(language) ? language : 'en'
  localStorage.setItem('grocery-language', locale)
  applyDocumentLanguage(locale)
})

export default i18n
